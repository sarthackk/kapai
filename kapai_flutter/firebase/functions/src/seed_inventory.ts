async function seed() {
  const batch = db.batch();
  let count = 0;

  for (const item of inventory) {
    const ref = db.collection('inventory').doc();
    batch.set(ref, {
      name: item.name,
      category: item.category,
      unit: item.unit,
      currentStock: 0,
      minThreshold: 0,
      isActive: true,
    });
    count++;

    // Firestore batch limit is 500
    if (count % 490 === 0) {
      await batch.commit();
      console.log(`Committed ${count} items`);
    }
  }

  await batch.commit();
  console.log(`✅ Seeded ${count} inventory items`);
}

seed().catch(console.error);
